"""Test notebook-derived SRS features as additive challengers to Prediction v2.

This experiment keeps the locked Prediction v2 architecture and fitting method
unchanged, then appends leakage-safe notebook SRS features generated by
``notebook_srs_elasticnet``. The frozen 2026 Prediction v2 model is never modified.

Three variants are predeclared before observing results:

* NEW_CORE: V2 + notebook EPA, PPD, and drive-conversion SRS differences.
* EFFICIENCY: V2 + SR, EPA, PPD, and drive-conversion SRS differences.
* ALL_COMPONENTS: V2 + the five notebook component SRS differences, including
  score-margin SRS. ``SRSdiff_Overall`` is intentionally excluded because it is
  exactly the average of the five component standardized ratings and therefore
  adds deterministic redundancy.

Every fold uses the exact common train/test game IDs available to both Prediction
v2 and the notebook feature materializer. The baseline Prediction v2 model is
refit on that same common training sample, so deltas isolate the value of the
added features rather than sample-composition differences.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

from cfb_analytics.analytics.notebook_srs_elasticnet import (
    NOTEBOOK_FEATURES,
    eligible_notebook,
    load_notebook_data,
)
from cfb_analytics.analytics.prediction_v1_integrity_audit import MIN_GAMES_VALUES
from cfb_analytics.analytics.prediction_v1_site_aware_challenger import (
    SITE_AWARE,
    TEST_SEASONS,
    eligible_site,
    fit_generic,
    load_data as load_prediction_v2_data,
    predict_generic,
    prepare_generic,
)
from cfb_analytics.analytics.walk_forward_baseline import DEFAULT_SEASONS

CHALLENGER_VERSION = "prediction-v2-notebook-srs-additive-v1"

NOTEBOOK_SR = "SRSdiff_SR_diff"
NOTEBOOK_EPA = "SRSdiff_EPA_diff"
NOTEBOOK_PPD = "SRSdiff_PPD_diff"
NOTEBOOK_DRIVE_CONV = "SRSdiff_DriveConv_diff"
NOTEBOOK_SPREAD = "SRSdiff_spread"
NOTEBOOK_OVERALL = "SRSdiff_Overall"

NEW_CORE = (NOTEBOOK_EPA, NOTEBOOK_PPD, NOTEBOOK_DRIVE_CONV)
EFFICIENCY = (NOTEBOOK_SR, NOTEBOOK_EPA, NOTEBOOK_PPD, NOTEBOOK_DRIVE_CONV)
ALL_COMPONENTS = (
    NOTEBOOK_SPREAD,
    NOTEBOOK_SR,
    NOTEBOOK_EPA,
    NOTEBOOK_PPD,
    NOTEBOOK_DRIVE_CONV,
)

VARIANTS: dict[str, tuple[str, ...]] = {
    "NEW_CORE": NEW_CORE,
    "EFFICIENCY": EFFICIENCY,
    "ALL_COMPONENTS": ALL_COMPONENTS,
}


def project_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _by_id(rows: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for row in rows:
        gid = row.get("gameId")
        if gid is None:
            continue
        key = str(gid)
        if key in out:
            raise ValueError(f"Duplicate gameId in challenger input: {key}")
        out[key] = row
    return out


def merge_common_rows(
    v2_rows: list[dict[str, Any]],
    notebook_rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Join V2 and notebook features by gameId with strict target/team checks."""
    v2 = _by_id(v2_rows)
    notebook = _by_id(notebook_rows)
    common = sorted(set(v2) & set(notebook))
    merged: list[dict[str, Any]] = []
    for gid in common:
        vrow = v2[gid]
        nrow = notebook[gid]
        if str(vrow.get("homeTeam")) != str(nrow.get("homeTeam")):
            raise ValueError(f"Home-team mismatch for game {gid}")
        if str(vrow.get("awayTeam")) != str(nrow.get("awayTeam")):
            raise ValueError(f"Away-team mismatch for game {gid}")
        v_margin = float(vrow["target_margin"])
        n_margin = float(nrow["target_margin"])
        if abs(v_margin - n_margin) > 1e-9:
            raise ValueError(f"Target mismatch for game {gid}: v2={v_margin} notebook={n_margin}")
        row = dict(vrow)
        for feature in NOTEBOOK_FEATURES:
            row[feature] = nrow.get(feature)
        merged.append(row)
    return merged


def _metrics(rows: list[dict[str, Any]], prediction_field: str) -> dict[str, float]:
    if not rows:
        return {"n": 0, "mae": float("nan"), "rmse": float("nan"), "winner": float("nan")}
    absolute: list[float] = []
    squared: list[float] = []
    correct = 0
    for row in rows:
        actual = float(row["actualHomeMargin"])
        prediction = float(row[prediction_field])
        absolute.append(abs(prediction - actual))
        squared.append((prediction - actual) ** 2)
        correct += int((prediction > 0.0) == (actual > 0.0))
    n = len(rows)
    return {
        "n": n,
        "mae": sum(absolute) / n,
        "rmse": math.sqrt(sum(squared) / n),
        "winner": correct / n,
    }


def _feature_tuple(extra: tuple[str, ...]) -> tuple[str, ...]:
    return tuple(SITE_AWARE) + tuple(extra)


def evaluate(
    raw_root: Path,
    processed_root: Path,
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    notebook = load_notebook_data(raw_root)
    v2 = load_prediction_v2_data(raw_root, processed_root)

    fold_rows: list[dict[str, Any]] = []
    per_game: list[dict[str, Any]] = []

    for min_games in MIN_GAMES_VALUES:
        v2_eligible = {
            season: [row for row in v2[season] if eligible_site(row, min_games)]
            for season in DEFAULT_SEASONS
        }
        notebook_eligible = {
            season: [row for row in notebook[season] if eligible_notebook(row, min_games)]
            for season in DEFAULT_SEASONS
        }
        common_by_season = {
            season: merge_common_rows(v2_eligible[season], notebook_eligible[season])
            for season in DEFAULT_SEASONS
        }

        for test_season in TEST_SEASONS:
            train = [
                row
                for season in DEFAULT_SEASONS
                if season < test_season
                for row in common_by_season[season]
            ]
            test = common_by_season[test_season]
            if not train or not test:
                raise ValueError(f"Missing common train/test rows for {test_season} min{min_games}")

            baseline_features = tuple(SITE_AWARE)
            baseline = fit_generic(prepare_generic(train, baseline_features))
            variant_models = {
                name: fit_generic(prepare_generic(train, _feature_tuple(extra)))
                for name, extra in VARIANTS.items()
            }

            fold_games: list[dict[str, Any]] = []
            for row in test:
                actual = float(row["target_margin"])
                base_prediction = predict_generic(baseline, row)
                out = {
                    "minGames": int(min_games),
                    "season": int(test_season),
                    "seasonType": row.get("seasonType"),
                    "week": int(row.get("week") or 0),
                    "gameId": str(row["gameId"]),
                    "homeTeam": row.get("homeTeam"),
                    "awayTeam": row.get("awayTeam"),
                    "actualHomeMargin": actual,
                    "predictionV2HomeMargin": base_prediction,
                }
                for feature in ALL_COMPONENTS:
                    out[feature] = float(row[feature])
                for name, model in variant_models.items():
                    field = f"{name}HomeMargin"
                    out[field] = predict_generic(model, row)
                fold_games.append(out)
                per_game.append(out)

            base_score = _metrics(fold_games, "predictionV2HomeMargin")
            variant_scores: dict[str, Any] = {}
            for name in VARIANTS:
                score = _metrics(fold_games, f"{name}HomeMargin")
                variant_scores[name] = {
                    **score,
                    "deltaMae": score["mae"] - base_score["mae"],
                    "deltaRmse": score["rmse"] - base_score["rmse"],
                    "deltaWinnerPP": (score["winner"] - base_score["winner"]) * 100.0,
                }

            fold_rows.append(
                {
                    "minGames": int(min_games),
                    "season": int(test_season),
                    "trainN": len(train),
                    "testN": len(test),
                    "predictionV2": base_score,
                    "variants": variant_scores,
                }
            )

    pooled: list[dict[str, Any]] = []
    for min_games in MIN_GAMES_VALUES:
        games = [row for row in per_game if row["minGames"] == min_games]
        base_score = _metrics(games, "predictionV2HomeMargin")
        variants: dict[str, Any] = {}
        for name in VARIANTS:
            score = _metrics(games, f"{name}HomeMargin")
            variants[name] = {
                **score,
                "deltaMae": score["mae"] - base_score["mae"],
                "deltaRmse": score["rmse"] - base_score["rmse"],
                "deltaWinnerPP": (score["winner"] - base_score["winner"]) * 100.0,
            }
        pooled.append(
            {
                "minGames": int(min_games),
                "n": len(games),
                "predictionV2": base_score,
                "variants": variants,
            }
        )

    stability: dict[str, Any] = {}
    for name in VARIANTS:
        rows = [
            {
                "minGames": fold["minGames"],
                "season": fold["season"],
                **fold["variants"][name],
            }
            for fold in fold_rows
        ]
        recent = [row for row in rows if row["season"] in (2023, 2024, 2025)]
        stability[name] = {
            "allFolds": len(rows),
            "meanDeltaMae": sum(row["deltaMae"] for row in rows) / len(rows),
            "meanDeltaRmse": sum(row["deltaRmse"] for row in rows) / len(rows),
            "meanDeltaWinnerPP": sum(row["deltaWinnerPP"] for row in rows) / len(rows),
            "maeWins": sum(row["deltaMae"] < 0.0 for row in rows),
            "rmseWins": sum(row["deltaRmse"] < 0.0 for row in rows),
            "recentFolds": len(recent),
            "recentMeanDeltaMae": sum(row["deltaMae"] for row in recent) / len(recent),
            "recentMeanDeltaRmse": sum(row["deltaRmse"] for row in recent) / len(recent),
            "recentMaeWins": sum(row["deltaMae"] < 0.0 for row in recent),
            "recentRmseWins": sum(row["deltaRmse"] < 0.0 for row in recent),
        }

    report = {
        "schemaVersion": 1,
        "challengerVersion": CHALLENGER_VERSION,
        "baselineFeatures": list(SITE_AWARE),
        "variants": {name: list(features) for name, features in VARIANTS.items()},
        "excludedNotebookFeature": NOTEBOOK_OVERALL,
        "reasonExcludedNotebookFeature": "deterministic average of the five component standardized SRS ratings",
        "testSeasons": list(TEST_SEASONS),
        "evaluation": "expanding-season OOS; exact common train and test game IDs; Prediction v2 refit on same common sample",
        "pooled": pooled,
        "folds": fold_rows,
        "stability": stability,
    }
    return report, per_game


def _print_score(label: str, score: dict[str, Any], baseline: dict[str, Any]) -> None:
    print(
        f"  {label:<14} MAE {score['mae']:.4f} ({score['deltaMae']:+.4f}) | "
        f"RMSE {score['rmse']:.4f} ({score['deltaRmse']:+.4f}) | "
        f"WIN {score['winner']:.3%} ({score['deltaWinnerPP']:+.3f}pp)"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Test additive notebook SRS features on Prediction v2")
    parser.add_argument("--raw-root", type=Path, default=Path("data/raw"))
    parser.add_argument("--processed-root", type=Path, default=Path("data/processed"))
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/processed/prediction_v2_notebook_feature_challenger.json"),
    )
    parser.add_argument(
        "--games-output",
        type=Path,
        default=Path("data/processed/prediction_v2_notebook_feature_challenger_games.json"),
    )
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    report, games = evaluate(args.raw_root, args.processed_root)

    print("PREDICTION V2 + NOTEBOOK SRS FEATURE CHALLENGER")
    print(f"Version: {CHALLENGER_VERSION}")
    print("Baseline: locked Prediction v2 architecture, refit on exact common sample")
    print("Negative delta = challenger better than V2.\n")

    for fold in report["folds"]:
        base = fold["predictionV2"]
        print(
            f"min{fold['minGames']} {fold['season']}: n={fold['testN']:,} train={fold['trainN']:,} | "
            f"V2 MAE {base['mae']:.4f} RMSE {base['rmse']:.4f} WIN {base['winner']:.3%}"
        )
        for name in VARIANTS:
            _print_score(name, fold["variants"][name], base)

    print("\nPOOLED COMMON SAMPLE")
    for row in report["pooled"]:
        base = row["predictionV2"]
        print(
            f"min{row['minGames']}: n={row['n']:,} | "
            f"V2 MAE {base['mae']:.4f} RMSE {base['rmse']:.4f} WIN {base['winner']:.3%}"
        )
        for name in VARIANTS:
            _print_score(name, row["variants"][name], base)

    print("\nSTABILITY")
    for name, row in report["stability"].items():
        print(
            f"{name}: ALL dMAE {row['meanDeltaMae']:+.4f} dRMSE {row['meanDeltaRmse']:+.4f} "
            f"MAE wins {row['maeWins']}/{row['allFolds']} RMSE wins {row['rmseWins']}/{row['allFolds']} | "
            f"RECENT dMAE {row['recentMeanDeltaMae']:+.4f} dRMSE {row['recentMeanDeltaRmse']:+.4f} "
            f"MAE wins {row['recentMaeWins']}/{row['recentFolds']} RMSE wins {row['recentRmseWins']}/{row['recentFolds']}"
        )

    for path, payload in ((args.output, report), (args.games_output, games)):
        if path.exists() and not args.overwrite:
            raise FileExistsError(f"Output exists: {path}; use --overwrite intentionally")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")

    print(f"Report: {args.output}")
    print(f"Matched games: {args.games_output}")


if __name__ == "__main__":
    main()
